def tampilkan_label(ax):
    for container in ax.containers:
        labels = []

        for bar in container:
            tinggi = bar.get_height()

            if np.isfinite(tinggi):
                labels.append(f'{tinggi:.2f}%')
            else:
                labels.append('')

        ax.bar_label(
            container,
            labels=labels,
            padding=4,
            fontsize=9,
            fontweight='bold'
        )

    # Memberikan ruang agar label di atas batang tidak terpotong
    ax.margins(y=0.15)


