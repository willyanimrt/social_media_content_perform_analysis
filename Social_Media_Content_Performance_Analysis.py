# Mengonversi kolom tanggal ke format datetime
df['Tanggal'] = pd.to_datetime(df['Tanggal'])

# Ekstraksi fitur waktu dari tanggal publish
df['Tahun'] = df['Tanggal'].dt.year
df['Bulan'] = df['Tanggal'].dt.month
df['Hari_Angka'] = df['Tanggal'].dt.day
df['Hari_dalam_Minggu'] = df['Tanggal'].dt.day_name()  # Nama hari (Monday, Tuesday, dll)

# Mapping nama hari ke Bahasa Indonesia agar mudah dianalisis
day_mapping = {
    'Monday': 'Senin',
    'Tuesday': 'Selasa',
    'Wednesday': 'Rabu',
    'Thursday': 'Kamis',
    'Friday': 'Jumat',
    'Saturday': 'Sabtu',
    'Sunday': 'Minggu',
}
df['Hari_Publish'] = df['Hari_dalam_Minggu'].map(day_mapping)

# Menghitung Total Extended Engagement (Interaksi Murni + Aksi Lanjutan)
df['Total_Engagement_Extended'] = (
    df['Like']
    + df['Comment']
    + df['Share']
    + df['Save']
    + df['Profile Visits']
    + df['Website Taps']
)

# Menghitung Target Utama: Extended Engagement Rate (%)
df['Engagement_Rate'] = (
    df['Total_Engagement_Extended'] / df['Total Impression'].replace(0, 1)
) * 100

# Menampilkan kolom-kolom hasil rekayasa fitur utama
print('--- CONTOH HASIL FEATURE ENGINEERING ---')
print(
    df[
        [
            'Tanggal',
            'Hari_Publish',
            'Jenis Konten',
            'tema konten',
            'kolaborasi',
            'Engagement_Rate',
        ]
    ].to_string(index=False)
)

"""# **Train and Testing Split**"""

from sklearn.model_selection import train_test_split

# Mendefinisikan target 'High_Performer' berdasarkan median dari Engagement_Rate
median_er = df['Engagement_Rate'].median()
df['High_Performer'] = (df['Engagement_Rate'] > median_er).astype(int)

# Menyiapkan fitur (X) DAN target (y) ---
feature_cols = ['Jenis Konten', 'tema konten', 'kolaborasi', 'Bulan', 'Hari_Publish']
X = pd.get_dummies(df[feature_cols], drop_first=True)
y = df['High_Performer']

print(f'Total Sampel Data: {len(X)} baris\n')

# --- TRAIN-TEST SPLIT ---
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.4, random_state=42
)

"""# **Model Evaluation**"""

# Inisialisasi Model Klasifikasi
models = {
    'Logistic Regression': LogisticRegression(
        random_state=42
    ),

    'Random Forest': RandomForestClassifier(
        random_state=42
    ),

    'XGBoost': XGBClassifier(
        random_state=42,
        eval_metric='logloss'
    )
}

# Evaluasi Model & Classification Report
for name, model in models.items():
  print(f'================ {name} ================' )

  # Training Model
  model.fit(X_train, y_train)

  # Prediksi
  y_pred = model.predict(X_test)

  # Menampilkan Akurasi & Laporan Detail
  acc = accuracy_score(y_test, y_pred)
  print(f'Akurasi Model: {acc * 100:.2f}%\n')

  print('Classification Report (Precision, Recall, F1-Score):')
  # zero_division=0 digunakan untuk menghindari warning jika ada kelas yang tidak terprediksi
  print(classification_report(y_test, y_pred, zero_division=0))
